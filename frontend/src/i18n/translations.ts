import type { LanguagePreference, ProblemDifficulty, ProblemStatus } from "../types/api";

export type Locale = "en" | "vi";

export function resolveLocale(pref: LanguagePreference): Locale {
  if (pref === "en" || pref === "vi") return pref;
  if (typeof navigator !== "undefined" && navigator.language.toLowerCase().startsWith("vi")) {
    return "vi";
  }
  return "en";
}

